import math

# Constants from IGMConstants.java
A = 6378137.0
F_INV = 298.257223563
F = 1.0 / F_INV
B = A * (1.0 - F)
ESQ = (A**2 - B**2) / (A**2)
E_PRIME_SQ = (A**2 - B**2) / (B**2)
K0 = 0.9996
P0_MMHG = 759.99
P0_HPA = 1013.25
PRESSURE_COEFF = 0.0000225577
PRESSURE_EXP = 5.2559

def dms_to_decimal(d, m, s, hemi):
    dec = d + m/60.0 + s/3600.0
    if hemi in ['S', 'W']:
        dec = -dec
    return dec

def get_central_meridian(lon):
    zone = int(math.floor((lon + 180.0) / 6.0)) + 1
    return (zone * 6.0) - 183.0

def calculate_scale_factor(lat, lon):
    lat_rad = math.radians(lat)
    lon_rad = math.radians(lon)
    lon0_rad = math.radians(get_central_meridian(lon))

    cesc = E_PRIME_SQ * math.cos(lat_rad)**2
    tesc = math.tan(lat_rad)**2
    aesc = (lon0_rad - lon_rad) * math.cos(lat_rad)

    k = K0 * (1.0 + (1.0 + cesc) * (aesc**2 / 2.0) +
              (5.0 - 4.0 * tesc + 42.0 * cesc + 13.0 * cesc**2 - 23.0 * E_PRIME_SQ) * (aesc**4 / 24.0) +
              (61.0 - 148.0 * tesc + 16.0 * tesc**2) * (aesc**6 / 720.0))
    return k

def calculate_mean_radius(lat):
    lat_rad = math.radians(lat)
    nn = A / math.sqrt(1.0 - ESQ * math.sin(lat_rad)**2)
    mm = (A * (1.0 - ESQ)) / (1.0 - ESQ * math.sin(lat_rad)**2)**1.5
    return math.sqrt(nn * mm)

def calculate_elevation_factor(rm, alt_orto):
    return rm / (rm + alt_orto)

def calculate_pressure_mmhg(alt_orto):
    return P0_MMHG * (1.0 - PRESSURE_COEFF * alt_orto)**PRESSURE_EXP

def calculate_pressure_hpa(alt_orto):
    return P0_HPA * (1.0 - PRESSURE_COEFF * alt_orto)**PRESSURE_EXP

