    public static double getEGM96Undulation(double lat, double lon) {
        if (lon > 180) lon -= 360;
        if (lon < -180) lon += 360;

        if (lat <= 0 && lat >= -30 && lon >= -75 && lon <= -55) {
            return interpolate(lat, lon, LATS_1DEG, LONS_1DEG, GEOID_GRID_1DEG);
        }

        return interpolate(lat, lon, LATS_10DEG, LONS_10DEG, GEOID_GRID);
    }

    private static double interpolate(double lat, double lon, double[] gridLats, double[] gridLons, double[][] grid) {
        int latIdx = -1;
        for (int i = 0; i < gridLats.length - 1; i++) {
            double maxLat = Math.max(gridLats[i], gridLats[i+1]);
            double minLat = Math.min(gridLats[i], gridLats[i+1]);
            if (lat <= maxLat && lat >= minLat) {
                latIdx = i;
                break;
            }
        }

        int lonIdx = -1;
        for (int i = 0; i < gridLons.length - 1; i++) {
            if (lon >= gridLons[i] && lon <= gridLons[i+1]) {
                lonIdx = i;
                break;
            }
        }

        if (latIdx == -1 || lonIdx == -1) return 0;

        double x1 = gridLons[lonIdx];
        double x2 = gridLons[lonIdx + 1];
        double y1 = gridLats[latIdx];
        double y2 = gridLats[latIdx + 1];

        double q11 = grid[latIdx][lonIdx];
        double q21 = grid[latIdx][lonIdx + 1];
        double q12 = grid[latIdx + 1][lonIdx];
        double q22 = grid[latIdx + 1][lonIdx + 1];

        double r1 = ((x2 - lon) / (x2 - x1)) * q11 + ((lon - x1) / (x2 - x1)) * q21;
        double r2 = ((x2 - lon) / (x2 - x1)) * q12 + ((lon - x1) / (x2 - x1)) * q22;

        return ((y2 - lat) / (y2 - y1)) * r1 + ((lat - y1) / (y2 - y1)) * r2;
    }
